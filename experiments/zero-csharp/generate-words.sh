#!/bin/sh
# Rewrites DockerWords.g.cs from the docker theme the slugger command embeds. Needs jq.
# Zero C# has no JSON parser worth shipping in 15 KB, so the words are baked in at build time:
# one string per list, words separated by a single space, and their counts as constants.
set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
theme="$here/../../src/Slugger/Infrastructure/Resources/docker.json"
out="$here/DockerWords.g.cs"

adjectives=$(jq -r '.adjectives.common | join(" ")' "$theme")
nouns=$(jq -r '[.nouns[].value] | join(" ")' "$theme")
adjective_count=$(jq -r '.adjectives.common | length' "$theme")
noun_count=$(jq -r '.nouns | length' "$theme")

cat > "$out" <<CS
// <auto-generated> by generate-words.sh from the built-in docker theme. Do not edit. </auto-generated>

namespace ZeroSlugger;

public static class DockerWords
{
    public const int AdjectiveCount = $adjective_count;
    public const int NounCount = $noun_count;

    public const string Adjectives = "$adjectives";

    public const string Nouns = "$nouns";
}
CS
